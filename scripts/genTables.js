console.log(`TSTEP           equ     ${T}`);
console.log(`PBASE           equ     ${PBASE}`);
console.log(`KA              equ     ${KA}`);
console.log(`KB              equ     ${KB}`);
console.log(`Z1_MIN          equ     ${z1Min}`);
console.log(`Z1_MAX          equ     ${z1Max}`);
